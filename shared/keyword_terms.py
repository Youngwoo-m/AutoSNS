"""구독 피드·이웃새글 제목에서 '지역+재난' 검색어를 뽑는 공통 로직.

각 프로젝트의 network_keywords.py 는 제목을 '어디서 가져오는지'만 다르고
(유튜브 구독 API / 네이버 이웃새글 스크래핑), 뽑아내는 규칙은 동일하다.
"""

SEARCH_DISASTER_TERMS = [
    "호우", "집중호우", "폭우", "태풍", "지진", "산사태", "폭염", "화재", "산불",
    "한파", "대설", "폭설", "침수", "홍수", "해일", "가뭄", "낙뢰", "열사병",
    "붕괴", "실종", "대피",
]
# 지역: 광역시도 + 자주 등장하는 시·군(제목에서 조합을 잡기 위함)
SEARCH_PLACE_TERMS = [
    "제천", "충북", "충청북도", "강원", "경기", "서울", "인천", "충남", "대전",
    "세종", "부산", "대구", "광주", "울산", "전북", "전남", "경북", "경남", "제주",
    "포항", "경주", "청주", "충주", "원주", "강릉", "춘천", "안동", "예천", "서산",
    "천안", "아산", "수원", "성남", "고양", "김해", "창원", "여수", "목포",
]


def queries_from_titles(titles):
    """재난 키워드가 든 제목만 골라 '지역+재난' 조합 검색어를 만든다(오염 방지)."""
    out = []
    for t in titles:
        disasters = [d for d in SEARCH_DISASTER_TERMS if d in t]
        if not disasters:
            continue  # 재난 무관 제목은 통째로 버린다
        places = [p for p in SEARCH_PLACE_TERMS if p in t]
        q = f"{places[0]} {disasters[0]}" if places else disasters[0]
        if q not in out:
            out.append(q)
    return out


