def is_disaster_relevant(title, extra=()):
    """제목에 재난·안전 관련 말이 하나라도 들면 True."""
    t = title or ""
    return any(w and w in t for w in list(RELEVANCE_TERMS) + list(extra or ()))


def queries_from_titles(titles):
    """재난 키워드가 든 제목만 골라 '지역+재난' 조합 검색어를 만든다(오염 방지)."""
    out = []
    for t in titles:
        disasters = [d for d in SEARCH_DISASTER_TERMS if d in t]
        if not disasters:
            continue  # 재난 무관 제목은 통째로 버린다
        places = [p for p in SEARCH_PLACE_TERMS if p in t]
        q = f"{places[0]} {disasters[0]}" if places else disasters[0]
        if q not in out:
            out.append(q)
    return out


