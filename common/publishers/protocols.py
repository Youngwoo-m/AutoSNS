"""서버 소유 발행 adapter 계약. prepare는 순수 함수여야 한다."""
from typing import Protocol, Mapping
from common.operations.runtime_models import PublicationContext, SubmissionPermit, SubmissionResult, LookupResult, VerificationResult

class PublicationAdapter(Protocol):
    def inspect_target(self, ctx: PublicationContext) -> dict: ...
    def prepare(self, ctx: PublicationContext, snapshot: Mapping) -> dict: ...
    def submit(self, ctx: PublicationContext, prepared: Mapping, permit: SubmissionPermit) -> SubmissionResult: ...
    def lookup(self, ctx: PublicationContext, attempt: Mapping) -> LookupResult: ...
    def verify(self, ctx: PublicationContext, remote_id: str, snapshot: Mapping) -> VerificationResult: ...
